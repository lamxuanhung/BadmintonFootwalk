/**
 * @file    uart_comm.c
 * @brief   UART receive driver based on circular DMA.
 * @details DMA fills s_rx_dma continuously. The driver tracks the total
 *          number of bytes written by DMA ("written") and the total number
 *          read by the application (s_read_total). Their difference is the
 *          number of unread bytes. "written" is built from the number of
 *          completed DMA laps (counted in the transfer-complete callback)
 *          plus the position inside the current lap (DMA remaining counter).
 *
 *          The whole file is compiled only when BSP_RX_ENABLE is 1.
 *
 *          Port-specific parts are isolated in RX_DMA_REMAINING() and
 *          rx_tc_pending(); adapt only those when moving to another MCU
 *          family.
 * @author  <author name>
 * @date    <yyyy-mm-dd>
 */

#include "uart_comm.h"

#if BSP_RX_ENABLE

#include "main.h"
#include <stddef.h>

/** Receive UART handle, generated by CubeMX. Selected by BSP_RX_UART. */
extern UART_HandleTypeDef BSP_RX_UART;

#if ((BSP_RX_DMA_SIZE & (BSP_RX_DMA_SIZE - 1U)) != 0U)
#error "BSP_RX_DMA_SIZE must be a power of two"
#endif

/** Index mask of the receive buffer. */
#define RX_MASK     ((uint32_t)(BSP_RX_DMA_SIZE - 1U))

/** Number of bytes DMA still has to write in the current lap (port-specific). */
#define RX_DMA_REMAINING()  __HAL_DMA_GET_COUNTER(BSP_RX_UART.hdmarx)

/* ------------------------------------------------------------------------- */
/* Private data                                                              */
/* ------------------------------------------------------------------------- */

static uint8_t           s_rx_dma[BSP_RX_DMA_SIZE]; /**< Buffer filled by DMA.            */
static volatile uint32_t s_laps;                    /**< Completed DMA laps (ISR).        */
static uint32_t          s_read_total;              /**< Bytes read so far (main loop).   */
static volatile uint8_t  s_overflow_flag;           /**< Data lost since last check.      */
static volatile uint8_t  s_rx_error;                /**< Error seen, needs service.       */
static volatile uint32_t s_err_count;               /**< UART error counter.              */
static uint32_t          s_overflow_count;          /**< Buffer overwrite counter.        */

/* ------------------------------------------------------------------------- */
/* Private functions                                                         */
/* ------------------------------------------------------------------------- */

/**
 * @brief   Check whether DMA completed a lap that the ISR has not counted yet.
 * @details Port-specific: reads the DMA transfer-complete flag.
 *
 * @retval 1  Transfer-complete flag is set.
 * @retval 0  Flag is clear.
 */
static uint8_t rx_tc_pending(void)
{
    return (__HAL_DMA_GET_FLAG(BSP_RX_UART.hdmarx,
                               __HAL_DMA_GET_TC_FLAG_INDEX(BSP_RX_UART.hdmarx)) != 0U) ? 1U : 0U;
}

/**
 * @brief   Compute the total number of bytes DMA has written since start.
 * @details Handles the short window where DMA has wrapped but the ISR has
 *          not yet incremented s_laps: the transfer-complete flag is then
 *          set and counted as one extra lap. The read is repeated until the
 *          flag and the lap counter are stable.
 *
 * @return  Total bytes written (wraps modulo 2^32, which is harmless because
 *          the buffer size divides 2^32).
 */
static uint32_t rx_get_written(void)
{
    uint32_t laps;
    uint32_t laps_after;
    uint32_t head;
    uint8_t tc_before;
    uint8_t tc_after;

    do {
        tc_before  = rx_tc_pending();
        laps       = s_laps;
        head       = BSP_RX_DMA_SIZE - (uint32_t)RX_DMA_REMAINING();
        tc_after   = rx_tc_pending();
        laps_after = s_laps;
    } while ((tc_before != tc_after) || (laps != laps_after));

    if (head >= BSP_RX_DMA_SIZE) {
        head = 0U;
    }
    return ((laps + tc_after) * BSP_RX_DMA_SIZE) + head;
}

/**
 * @brief   Restart reception after a UART error if it stopped.
 * @details Runs in the main loop. If HAL still reports the receiver as busy
 *          the error was non-fatal and nothing is restarted.
 */
static void rx_service(void)
{
    if (s_rx_error != 0U) {
        s_rx_error = 0U;
        if (BSP_RX_UART.RxState != HAL_UART_STATE_BUSY_RX) {
            (void)HAL_UART_AbortReceive(&BSP_RX_UART);
            (void)Uart_RxStart();
            s_overflow_flag = 1U;       /* unread data discarded */
        }
    }
}

/* ------------------------------------------------------------------------- */
/* Public functions                                                          */
/* ------------------------------------------------------------------------- */

uint8_t Uart_RxStart(void)
{
    s_laps = 0U;
    s_read_total = 0U;

    /* Remove a stale transfer-complete flag from a previous run. */
    __HAL_DMA_CLEAR_FLAG(BSP_RX_UART.hdmarx,
                         __HAL_DMA_GET_TC_FLAG_INDEX(BSP_RX_UART.hdmarx));

    if (HAL_UART_Receive_DMA(&BSP_RX_UART, s_rx_dma, (uint16_t)BSP_RX_DMA_SIZE) != HAL_OK) {
        return 0U;
    }

    /* Half-transfer interrupt is not needed; keep only transfer-complete. */
    __HAL_DMA_DISABLE_IT(BSP_RX_UART.hdmarx, DMA_IT_HT);
    return 1U;
}

uint16_t Uart_RxAvailable(void)
{
    uint32_t written;
    uint32_t pending;

    rx_service();

    written = rx_get_written();
    pending = written - s_read_total;

    /*
     * pending == buffer size means DMA is about to overwrite the oldest
     * byte, so treat it (and anything larger) as an overwrite.
     */
    if (pending >= BSP_RX_DMA_SIZE) {
        s_overflow_flag = 1U;
        s_overflow_count++;
        s_read_total = written;         /* drop everything, resynchronize */
        return 0U;
    }
    return (uint16_t)pending;
}

uint8_t Uart_RxRead(uint8_t *byte)
{
    if (byte == NULL) {
        return 0U;
    }
    if (Uart_RxAvailable() == 0U) {
        return 0U;
    }
    *byte = s_rx_dma[s_read_total & RX_MASK];
    s_read_total++;
    return 1U;
}

uint16_t Uart_RxReadBuf(uint8_t *buf, uint16_t max)
{
    uint16_t n;
    uint16_t i;

    if ((buf == NULL) || (max == 0U)) {
        return 0U;
    }

    n = Uart_RxAvailable();
    if (n > max) {
        n = max;
    }
    for (i = 0U; i < n; i++) {
        buf[i] = s_rx_dma[(s_read_total + i) & RX_MASK];
    }
    s_read_total += n;
    return n;
}

uint8_t Uart_RxOverflowTaken(void)
{
    uint8_t flag = s_overflow_flag;

    s_overflow_flag = 0U;
    return flag;
}

uint32_t Uart_GetErrorCount(void)
{
    return s_err_count;
}

uint32_t Uart_GetOverflowCount(void)
{
    return s_overflow_count;
}

/* ------------------------------------------------------------------------- */
/* HAL callbacks                                                             */
/* ------------------------------------------------------------------------- */

/**
 * @brief   HAL receive-complete callback (defined once for the project).
 * @details In circular mode this is called every time DMA wraps around, so
 *          it counts completed laps. Only reacts to the receive UART.
 *
 * @param[in] huart  UART handle that completed a receive lap.
 */
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart == &BSP_RX_UART) {
        s_laps++;
    }
}

/**
 * @brief   HAL error callback (defined once for the project).
 * @details Only records the error; the restart is done in the main loop
 *          (rx_service) so that no blocking HAL call runs in interrupt
 *          context.
 *
 * @param[in] huart  UART handle that reported the error.
 */
void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart)
{
    if (huart == &BSP_RX_UART) {
        s_err_count++;
        s_rx_error = 1U;
    }
}

#endif /* BSP_RX_ENABLE */
