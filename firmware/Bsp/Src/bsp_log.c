/**
 * @file    bsp_log.c
 * @brief   Non-blocking logging over UART (ring buffer + DMA/interrupt TX).
 * @details Single producer (main loop, Log_Write) and single consumer
 *          (transmit-complete callback). The producer owns s_head, the
 *          consumer owns s_tail, so no lock is needed except around starting
 *          a transfer.
 *
 *          CubeMX requirements for the log UART:
 *            - USART global interrupt enabled (transmit-complete event).
 *            - When BSP_LOG_USE_DMA is 1: DMA TX request in Normal mode and
 *              the DMA channel interrupt enabled.
 *
 *          Porting notes: on MCUs with a data cache (for example Cortex-M7)
 *          the buffer must be cache-clean before a DMA transfer starts.
 * @author  <author name>
 * @date    <yyyy-mm-dd>
 */

#include "bsp_log.h"
#include "bsp_format.h"
#include "main.h"
#include <stdarg.h>

/** Log UART handle, generated by CubeMX. Selected by BSP_LOG_UART. */
extern UART_HandleTypeDef BSP_LOG_UART;

#if ((BSP_LOG_BUF_SIZE & (BSP_LOG_BUF_SIZE - 1U)) != 0U)
#error "BSP_LOG_BUF_SIZE must be a power of two"
#endif
#if (BSP_LOG_LINE_MAX < 32U)
#error "BSP_LOG_LINE_MAX must be at least 32"
#endif

/** Index mask of the ring buffer. */
#define LOG_MASK    ((uint16_t)(BSP_LOG_BUF_SIZE - 1U))

#if BSP_LOG_USE_DMA
#define LOG_TX_START(p, n)  HAL_UART_Transmit_DMA(&BSP_LOG_UART, (p), (n))
#else
#define LOG_TX_START(p, n)  HAL_UART_Transmit_IT(&BSP_LOG_UART, (p), (n))
#endif

/* ------------------------------------------------------------------------- */
/* Private data                                                              */
/* ------------------------------------------------------------------------- */

static uint8_t           s_buf[BSP_LOG_BUF_SIZE];  /**< Ring buffer.                    */
static volatile uint16_t s_head;                   /**< Next write index (main loop).   */
static volatile uint16_t s_tail;                   /**< Next index to send (TX ISR).    */
static volatile uint16_t s_tx_len;                 /**< Bytes in the transfer running.  */
static volatile uint32_t s_dropped;                /**< Dropped message counter.        */
static uint8_t           s_level = (uint8_t)BSP_LOG_LEVEL; /**< Run-time level.         */

/** Level tag characters, indexed by level (0 = unused). */
static const char s_level_tag[] = { '-', 'E', 'W', 'I', 'D' };

/* ------------------------------------------------------------------------- */
/* Private functions                                                         */
/* ------------------------------------------------------------------------- */

/**
 * @brief   Start sending the next contiguous chunk of the ring buffer.
 * @details Safe to call from the main loop and from the transmit-complete
 *          callback. If a transfer is marked as running but the UART is
 *          already READY, the transfer was aborted by an error, so it is
 *          retried from the unsent data.
 */
static void log_kick(void)
{
    uint32_t primask = __get_PRIMASK();
    uint16_t head;
    uint16_t tail;
    uint16_t len;

    __disable_irq();

    if (s_tx_len != 0U) {
        if (BSP_LOG_UART.gState == HAL_UART_STATE_READY) {
            s_tx_len = 0U;              /* aborted by an error: retry */
        } else {
            __set_PRIMASK(primask);     /* transfer still running */
            return;
        }
    }

    head = s_head;
    tail = s_tail;
    if (head != tail) {
        /* Send up to the end of the buffer; the rest follows in the next chunk. */
        len = (head > tail) ? (uint16_t)(head - tail)
                            : (uint16_t)(BSP_LOG_BUF_SIZE - tail);
        s_tx_len = len;
        if (LOG_TX_START(&s_buf[tail], len) != HAL_OK) {
            s_tx_len = 0U;              /* UART busy: Log_Task retries later */
        }
    }

    __set_PRIMASK(primask);
}

/**
 * @brief   Write the "[tick][L] " prefix into a buffer.
 *
 * @param[in]  level  Log level (1..4), selects the tag character.
 * @param[out] buf    Destination buffer.
 * @param[in]  size   Size of @p buf in bytes.
 *
 * @return Number of characters written (without the terminating NUL).
 */
static int log_make_prefix(uint8_t level, char *buf, size_t size)
{
    int n;

#if BSP_LOG_TIMESTAMP
    n = BSP_SNPRINTF(buf, size, "[%lu][%c] ",
                     (unsigned long)BSP_LOG_GET_TICK(), s_level_tag[level]);
#else
    n = BSP_SNPRINTF(buf, size, "[%c] ", s_level_tag[level]);
#endif

    if (n < 0) {
        return 0;
    }
    if ((size_t)n >= size) {
        n = (int)size - 1;
    }
    return n;
}

/**
 * @brief   Check whether a message of this level must be produced.
 *
 * @param[in] level  Message level.
 *
 * @retval 1  Level is valid and not above the run-time level.
 * @retval 0  Message must be ignored.
 */
static uint8_t log_level_enabled(uint8_t level)
{
    if ((level == BSP_LOG_LEVEL_NONE) || (level > BSP_LOG_LEVEL_DEBUG)) {
        return 0U;
    }
    return (level <= s_level) ? 1U : 0U;
}

/* ------------------------------------------------------------------------- */
/* Public functions                                                          */
/* ------------------------------------------------------------------------- */

uint16_t Log_Write(const char *data, uint16_t len)
{
    uint16_t head;
    uint16_t used;
    uint16_t i;

    if ((data == NULL) || (len == 0U)) {
        return 0U;
    }

    head = s_head;
    used = (uint16_t)((uint16_t)(head - s_tail) & LOG_MASK);

    /* One byte stays free so that head == tail always means "empty". */
    if (len > (uint16_t)(BSP_LOG_BUF_SIZE - 1U - used)) {
        s_dropped++;
        return 0U;
    }

    for (i = 0U; i < len; i++) {
        s_buf[(uint16_t)((head + i) & LOG_MASK)] = (uint8_t)data[i];
    }
    s_head = (uint16_t)((head + len) & LOG_MASK);

    log_kick();
    return len;
}

