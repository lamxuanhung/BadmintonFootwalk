void Log_Printf(const char *fmt, ...)
{
    char line[BSP_LOG_LINE_MAX];
    va_list ap;
    int n;

    va_start(ap, fmt);
    n = BSP_VSNPRINTF(line, sizeof(line), fmt, ap);
    va_end(ap);

    if (n <= 0) {
        return;
    }
    if ((size_t)n >= sizeof(line)) {
        n = (int)sizeof(line) - 1;      /* truncated */
    }
    (void)Log_Write(line, (uint16_t)n);
}

void Log_Print(uint8_t level, const char *fmt, ...)
{
    char line[BSP_LOG_LINE_MAX];
    va_list ap;
    int n;
    int m;
    size_t room;

    if (log_level_enabled(level) == 0U) {
        return;
    }

    n = log_make_prefix(level, line, sizeof(line));
    room = sizeof(line) - (size_t)n - 2U;       /* keep space for "\r\n" */

    va_start(ap, fmt);
    m = BSP_VSNPRINTF(&line[n], room, fmt, ap);
    va_end(ap);

    if (m < 0) {
        m = 0;
    }
    if ((size_t)m >= room) {
        m = (int)room - 1;                      /* truncated */
    }
    n += m;
    line[n++] = '\r';
    line[n++] = '\n';

    (void)Log_Write(line, (uint16_t)n);
}

#if BSP_LOG_ENABLE_HEXDUMP
void Log_HexDump(uint8_t level, const char *label, const uint8_t *data, uint16_t len)
{
    static const char hex[] = "0123456789ABCDEF";
    char line[BSP_LOG_LINE_MAX];
    int n;
    int m;
    uint16_t i;

    if (log_level_enabled(level) == 0U) {
        return;
    }

    n = log_make_prefix(level, line, sizeof(line));
    m = BSP_SNPRINTF(&line[n], sizeof(line) - (size_t)n, "%s[%u]:",
                     (label != NULL) ? label : "", (unsigned)len);
    if (m < 0) {
        m = 0;
    }
    n += m;
    if (n > ((int)sizeof(line) - 6)) {
        n = (int)sizeof(line) - 6;              /* keep room for "..." and "\r\n" */
    }

    /* Each byte needs 3 characters (" XX"). */
    for (i = 0U; (data != NULL) && (i < len) && ((size_t)n + 3U <= (sizeof(line) - 6U)); i++) {
        line[n++] = ' ';
        line[n++] = hex[(data[i] >> 4) & 0x0FU];
        line[n++] = hex[data[i] & 0x0FU];
    }
    if (i < len) {
        line[n++] = '.';
        line[n++] = '.';
        line[n++] = '.';
    }
    line[n++] = '\r';
    line[n++] = '\n';

    (void)Log_Write(line, (uint16_t)n);
}
#endif /* BSP_LOG_ENABLE_HEXDUMP */

void Log_SetLevel(uint8_t level)
{
    if (level > BSP_LOG_LEVEL_DEBUG) {
        level = (uint8_t)BSP_LOG_LEVEL_DEBUG;
    }
    s_level = level;
}

uint8_t Log_GetLevel(void)
{
    return s_level;
}

uint32_t Log_GetDroppedCount(void)
{
    return s_dropped;
}

uint8_t Log_IsIdle(void)
{
    return ((s_head == s_tail) && (s_tx_len == 0U)) ? 1U : 0U;
}

void Log_Task(void)
{
    log_kick();
}

/* ------------------------------------------------------------------------- */
/* HAL callback                                                              */
/* ------------------------------------------------------------------------- */

/**
 * @brief   HAL transmit-complete callback (defined once for the project).
 * @details Advances the read index past the chunk just sent and starts the
 *          next chunk. Only reacts to the log UART.
 *
 * @param[in] huart  UART handle that finished transmitting.
 */
void HAL_UART_TxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart == &BSP_LOG_UART) {
        s_tail = (uint16_t)((s_tail + s_tx_len) & LOG_MASK);
        s_tx_len = 0U;
        log_kick();
    }
}

